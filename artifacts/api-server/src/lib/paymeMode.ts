/**
 * Единый источник правды: включён ли Payme в ТЕСТОВОМ (песочница) режиме.
 *
 * Ошибиться тут можно в две противоположные стороны, поэтому решается это
 * везде одинаково:
 *   - Вебхук / сертификация песочницы: тест-режим должен быть ВКЛючён только
 *     при явном флаге, иначе вызовы песочницы уйдут в боевой путь и упадут.
 *   - Ссылки на оплату (checkout): если флаг пропал или кривой — по умолчанию
 *     ПРОДАКШЕН. Увести реального плательщика на checkout.test.paycom.uz —
 *     значит «оплатил, деньги не пришли».
 *
 * Строгая проверка `=== "true"` хрупкая: панели хостинга (Replit Secrets,
 * .env, docker) отдают значение то в кавычках, то в другом регистре, то как
 * `1`/`yes`/`on`. Любое из них — «включено», всё прочее (пусто, "false",
 * мусор) — ВЫКЛючено / продакшен, безопасный дефолт для движения денег.
 */
export function isPaymeTestMode(): boolean {
  const raw = process.env["PAYME_TEST_MODE"];
  if (raw == null) return false;
  const v = String(raw).trim().replace(/^["']|["']$/g, "").trim().toLowerCase();
  return v === "true" || v === "1" || v === "yes" || v === "on";
}
